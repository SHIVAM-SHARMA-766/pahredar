package scan

import (
	"net/http"
	"strings"
)

// WAF detection by response fingerprint. Signatures are matched against
// response headers, cookies, and the body of a blocked response. This is a
// heuristic — a negative result does not mean no WAF.

type wafSig struct {
	name    string
	headers map[string]string // header name -> substring (empty = presence)
	cookies []string          // cookie-name substrings
	body    []string          // body substrings (on a block page)
}

var wafSigs = []wafSig{
	{name: "Cloudflare", headers: map[string]string{"Server": "cloudflare", "CF-RAY": ""}, cookies: []string{"__cf_bm", "cf_clearance"}, body: []string{"Attention Required! | Cloudflare", "cf-error-details"}},
	{name: "Akamai", headers: map[string]string{"Server": "AkamaiGHost", "X-Akamai-Transformed": ""}, body: []string{"Reference&#32;&#35;", "akamai"}},
	{name: "AWS WAF / CloudFront", headers: map[string]string{"X-Amz-Cf-Id": "", "Server": "CloudFront"}, body: []string{"Request blocked", "Generated by cloudfront"}},
	{name: "Imperva / Incapsula", headers: map[string]string{"X-Iinfo": "", "X-CDN": "Incapsula"}, cookies: []string{"incap_ses", "visid_incap"}, body: []string{"Incapsula incident ID", "_Incapsula_Resource"}},
	{name: "Sucuri", headers: map[string]string{"Server": "Sucuri/Cloudproxy", "X-Sucuri-ID": ""}, body: []string{"Access Denied - Sucuri Website Firewall"}},
	{name: "F5 BIG-IP ASM", cookies: []string{"TS", "BIGipServer"}, body: []string{"The requested URL was rejected"}},
	{name: "Fastly", headers: map[string]string{"X-Served-By": "", "Fastly-Debug-Digest": ""}, body: []string{"Fastly error"}},
	{name: "Azure Front Door", headers: map[string]string{"X-Azure-Ref": ""}},
	{name: "StackPath / MaxCDN", headers: map[string]string{"Server": "StackPath"}},
	{name: "Wordfence", body: []string{"Generated by Wordfence", "Your access to this site has been limited"}},
	{name: "ModSecurity", headers: map[string]string{"Server": "Mod_Security"}, body: []string{"Mod_Security", "This error was generated by Mod_Security", "not acceptable"}},
}

// detectWAF inspects a response and returns the WAF/CDN name (if any) and
// whether this particular response looks like a block.
func detectWAF(resp *http.Response, body []byte) (name string, blocked bool) {
	lowerBody := strings.ToLower(string(body))
	setCookie := strings.ToLower(strings.Join(resp.Header.Values("Set-Cookie"), " "))
	for _, sig := range wafSigs {
		if sig.matches(resp, lowerBody, setCookie) {
			name = sig.name
			break
		}
	}
	blocked = isBlockStatus(resp.StatusCode)
	// A block page from a WAF is a strong signal even on a 200.
	if name != "" {
		for _, sig := range wafSigs {
			if sig.name == name {
				for _, b := range sig.body {
					if strings.Contains(lowerBody, strings.ToLower(b)) {
						blocked = true
					}
				}
			}
		}
	}
	return name, blocked
}

func (s wafSig) matches(resp *http.Response, lowerBody, setCookie string) bool {
	for h, want := range s.headers {
		v := resp.Header.Get(h)
		if v == "" {
			continue
		}
		if want == "" || strings.Contains(strings.ToLower(v), strings.ToLower(want)) {
			return true
		}
	}
	for _, c := range s.cookies {
		if strings.Contains(setCookie, strings.ToLower(c)) {
			return true
		}
	}
	for _, b := range s.body {
		if strings.Contains(lowerBody, strings.ToLower(b)) {
			return true
		}
	}
	return false
}

// isBlockStatus reports whether a status code commonly signals a WAF block.
func isBlockStatus(code int) bool {
	switch code {
	case http.StatusForbidden, http.StatusNotAcceptable, http.StatusTooManyRequests, 419, 418:
		return true
	}
	return false
}
